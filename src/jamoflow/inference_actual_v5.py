def _ratio_of_medians(candidate: np.ndarray, reference: np.ndarray) -> Any:
    return 1 - np.median(candidate, axis=(-3, -2, -1)) / np.median(
        reference, axis=(-3, -2, -1)
    )


def three_way_paired_latency(
    candidate_ms: np.ndarray,
    reference_ms: np.ndarray,
    *,
    session_order: tuple[str, ...] = ACTUAL_INFERENCE_V5_SESSIONS,
    seed_order: tuple[int, ...] = FINAL_SEEDS,
    bootstrap_repetitions: int = ACTUAL_INFERENCE_V5_BOOTSTRAP_REPETITIONS,
    bootstrap_seed: int = ACTUAL_INFERENCE_V5_BOOTSTRAP_SEED,
    chunk_size: int = 128,
) -> ThreeWayPairedLatency:
    """Three-axis crossed bootstrap after collapsing timing repetitions."""

    candidate = np.asarray(candidate_ms, dtype=np.float64)
    reference = np.asarray(reference_ms, dtype=np.float64)
    if (
        candidate.ndim != 4
        or candidate.shape != reference.shape
        or candidate.shape[:2] != (len(session_order), len(seed_order))
        or len(session_order) < 2
        or len(set(session_order)) != len(session_order)
        or len(seed_order) < 2
        or len(set(seed_order)) != len(seed_order)
        or candidate.shape[2] < 2
        or candidate.shape[3] < 1
        or bootstrap_repetitions <= 0
        or chunk_size <= 0
        or not np.isfinite(candidate).all()
        or not np.isfinite(reference).all()
        or np.any(candidate <= 0)
        or np.any(reference <= 0)
    ):
        raise ValueError(
            "three-way timings must be positive session-seed-prompt-repetition arrays"
        )
    candidate_cells = np.median(candidate, axis=3)
    reference_cells = np.median(reference, axis=3)
    point = float(
        1 - np.median(candidate_cells) / np.median(reference_cells)
    )
    session_count, seed_count, prompt_count = candidate_cells.shape
    rng = np.random.default_rng(bootstrap_seed)
    bootstrap = np.empty(bootstrap_repetitions, dtype=np.float64)
    for start in range(0, bootstrap_repetitions, chunk_size):
        size = min(chunk_size, bootstrap_repetitions - start)
        sessions = rng.integers(0, session_count, size=(size, session_count))
        seeds = rng.integers(0, seed_count, size=(size, seed_count))
        prompts = rng.integers(0, prompt_count, size=(size, prompt_count))
        candidate_crossed = candidate_cells[
            sessions[:, :, None, None],
            seeds[:, None, :, None],
            prompts[:, None, None, :],
        ]
        reference_crossed = reference_cells[
            sessions[:, :, None, None],
            seeds[:, None, :, None],
            prompts[:, None, None, :],
        ]
        bootstrap[start : start + size] = 1 - np.median(
            candidate_crossed, axis=(1, 2, 3)
        ) / np.median(reference_crossed, axis=(1, 2, 3))
    per_session = {
        session: float(
            1
            - np.median(candidate_cells[index])
            / np.median(reference_cells[index])
        )
        for index, session in enumerate(session_order)
    }
    per_seed = {
        str(seed): float(
            1
            - np.median(candidate_cells[:, index, :])
            / np.median(reference_cells[:, index, :])
        )
        for index, seed in enumerate(seed_order)
    }
    session_points = np.asarray(tuple(per_session.values()), dtype=np.float64)
    seed_points = np.asarray(tuple(per_seed.values()), dtype=np.float64)
    return ThreeWayPairedLatency(
        session_order=session_order,
        seed_order=seed_order,
        session_count=session_count,
        seed_count=seed_count,
        prompt_count=prompt_count,
        repetitions_per_prompt=candidate.shape[3],
        candidate_median_ms=float(np.median(candidate_cells)),
        reference_median_ms=float(np.median(reference_cells)),
        crossed_median_latency_reduction=point,
        bootstrap_repetitions=bootstrap_repetitions,
        bootstrap_seed=bootstrap_seed,
        bootstrap_design=(
            "crossed independent timing sessions x model seeds x shared prompts; "
            "within-cell repetitions collapsed by median"
        ),
        bootstrap_percentile_95_lower=float(np.percentile(bootstrap, 2.5)),
        bootstrap_percentile_95_upper=float(np.percentile(bootstrap, 97.5)),
        positive_session_count=int(np.sum(session_points > 0)),
        target_session_count=int(
            np.sum(session_points >= ACTUAL_INFERENCE_V5_MINIMUM_REDUCTION)
        ),
        positive_seed_count=int(np.sum(seed_points > 0)),
        median_session_point_reduction=float(np.median(session_points)),
        median_seed_point_reduction=float(np.median(seed_points)),
        per_session=per_session,
        per_seed=per_seed,
    )


