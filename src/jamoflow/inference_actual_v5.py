def validate_runtime_counter_arrays(
    counters: Mapping[str, np.ndarray],
    *,
    requires_entropy_router: bool,
    mode: str,
    emitted_output_bytes: np.ndarray,
) -> None:
    """Verify high-level timed-path identities for every measured trial."""

    if mode not in ACTUAL_INFERENCE_V5_MODES or set(counters) != set(
        RUNTIME_COUNTER_NAMES
    ):
        raise ValueError("actual-inference runtime counter schema differs")
    emitted = np.asarray(emitted_output_bytes)
    if emitted.ndim != 2 or not np.issubdtype(emitted.dtype, np.integer):
        raise ValueError("emitted-output counter shape differs")
    values: dict[str, np.ndarray] = {}
    for name in RUNTIME_COUNTER_NAMES:
        value = np.asarray(counters[name])
        if (
            value.shape != emitted.shape
            or not np.issubdtype(value.dtype, np.integer)
            or np.any(value < 0)
        ):
            raise ValueError(f"runtime counter differs: {name}")
        values[name] = value.astype(np.int64, copy=False)
    emitted = emitted.astype(np.int64, copy=False)
    consume = emitted - 1
    observed = ACTUAL_INFERENCE_V5_PROMPT_BYTES + consume
    if (
        np.any(emitted < ACTUAL_INFERENCE_V5_CONTINUATION_BYTES)
        or np.any(emitted > ACTUAL_INFERENCE_V5_MAXIMUM_OUTPUT_BYTES)
        or np.any(values["parallel_prefill_calls"] != 1)
        or np.any(values["main_consume_calls"] != consume)
        or np.any(values["selector_observed_bytes"] != observed)
        or np.any(values["explicit_device_synchronizations_inside_timing"] != 2)
    ):
        raise ValueError("runtime core counter identities differ")
    if requires_entropy_router:
        if (
            np.any(values["router_forward_calls"] != 1 + consume)
            or np.any(values["router_scored_bytes"] != observed)
        ):
            raise ValueError("entropy router was not included in timed execution")
    elif (
        np.any(values["router_forward_calls"] != 0)
        or np.any(values["router_scored_bytes"] != 0)
    ):
        raise ValueError("structural runtime contains entropy-router work")
    expected_readbacks = (
        emitted
        if mode == "free_running_utf8_greedy"
        else np.zeros_like(emitted)
    ) + (1 + consume if requires_entropy_router else 0)
    if np.any(
        values["device_to_host_readbacks_inside_timing"]
        != expected_readbacks
    ):
        raise ValueError("timed device-to-host readback identity differs")
    if mode == "controlled_replay":
        if (
            np.any(emitted != ACTUAL_INFERENCE_V5_CONTINUATION_BYTES)
            or any(
                np.any(values[name] != 0)
                for name in (
                    "argmax_calls",
                    "utf8_mask_calls",
                    "utf8_dfa_advances",
                    "stop_checks",
                )
            )
        ):
            raise ValueError("controlled replay contains free-generation work")
    elif any(
        np.any(values[name] != emitted)
        for name in (
            "argmax_calls",
            "utf8_mask_calls",
            "utf8_dfa_advances",
            "stop_checks",
        )
    ):
        raise ValueError("free-running generation work is outside timed execution")


def _output_content_sha256(
    *, seed: int, role: str, prompt_index: int, output: bytes
) -> str:
    digest = hashlib.sha256()
    digest.update(b"JamoFlow/actual-v5/free-output/v1\0")
    digest.update(int(seed).to_bytes(8, "big", signed=False))
    digest.update(role.encode("ascii"))
    digest.update(int(prompt_index).to_bytes(8, "big", signed=False))
    digest.update(len(output).to_bytes(8, "big", signed=False))
    digest.update(output)
    return digest.hexdigest()


